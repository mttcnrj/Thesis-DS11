"""Gate G0 (Section 2.1, D16): choose the laptop that runs everything and record gates/G00_machine.json.

Run on BOTH laptops (PowerShell) and paste the results:
    Get-CimInstance Win32_VideoController | Select-Object Name
    nvidia-smi --query-gpu=name,memory.total --format=csv,noheader          # NVIDIA laptops only
    Get-CimInstance Win32_Processor | Select-Object Name, NumberOfCores, NumberOfLogicalProcessors

Then, for example:
    python scripts/record_g0.py \\
      --laptop "Baltazar|Intel(R) UHD Graphics;NVIDIA GeForce RTX 4060 Laptop GPU|NVIDIA GeForce RTX 4060 Laptop GPU, 8188 MiB|8" \\
      --laptop "Serrano|AMD Radeon(TM) Graphics||6"
Format per laptop: name|Win32_VideoController names (;-separated)|nvidia-smi line (empty if none)|physical cores

Rules: only NVIDIA GPUs count. Both NVIDIA -> higher-tier card (more VRAM, then higher tier number, then newer
generation; use --choose to override after comparing nvidia-smi). One NVIDIA -> that laptop. Neither -> more cores.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import yaml  # noqa: E402

from pasig.config import root  # noqa: E402
from pasig.gates import record_gate  # noqa: E402


def parse(spec: str) -> dict:
    name, gpus, smi, cores = (spec.split("|") + ["", "", "", "0"])[:4]
    gpus = [g.strip() for g in gpus.split(";") if g.strip()]
    nvidia = [g for g in gpus if "NVIDIA" in g.upper()]
    vram = 0.0
    m = re.search(r"([\d.]+)\s*MiB", smi or "")
    if m:
        vram = float(m.group(1)) / 1024
    model = (smi.split(",")[0].strip() if smi else (nvidia[0] if nvidia else ""))
    mm = re.search(r"(\d)(\d)(\d{2})", model)            # RTX 4060 -> generation 40, tier 60
    gen, tier = (int(mm.group(1) + mm.group(2)), int(mm.group(3))) if mm else (0, 0)
    return {"name": name, "gpus": gpus, "nvidia": nvidia, "nvidia_smi": smi, "vram_gb": round(vram, 1),
            "gpu_model": model, "generation": gen, "tier": tier, "physical_cores": int(cores or 0)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--laptop", action="append", required=True)
    ap.add_argument("--choose", help="override when both have NVIDIA GPUs (name of the laptop)")
    a = ap.parse_args()
    lt = [parse(s) for s in a.laptop]
    nv = [x for x in lt if x["nvidia"]]
    if a.choose:
        chosen, reason = next(x for x in lt if x["name"] == a.choose), "manual choice after comparing nvidia-smi"
    elif len(nv) >= 2:
        chosen = max(nv, key=lambda x: (x["vram_gb"], x["tier"], x["generation"]))
        reason = "both have NVIDIA GPUs: higher-tier card (VRAM, tier, generation)"
    elif len(nv) == 1:
        chosen, reason = nv[0], "only laptop with an NVIDIA GPU"
    else:
        chosen = max(lt, key=lambda x: x["physical_cores"])
        reason = "no NVIDIA GPU: laptop with more physical CPU cores"
    record_gate("G0", "machine", True, "Section 2.1: NVIDIA only; both NVIDIA -> higher tier (nvidia-smi); one -> that "
                "laptop; neither -> more CPU cores", {"laptops": lt, "reason": reason}, decision=chosen["name"])
    p = root() / "configs" / "compute.yaml"
    cur = yaml.safe_load(p.read_text()) if p.exists() else {}
    cur = cur or {}
    cur["machine"] = {"name": chosen["name"], "gpu": chosen["gpu_model"] or None, "physical_cores": chosen["physical_cores"],
                      "python_in": "WSL2 Ubuntu" if chosen["nvidia"] else "native Windows"}
    p.write_text("# GENERATED by G0 (machine), G13, G14, G15. Do not edit by hand.\n" + yaml.safe_dump(cur, sort_keys=False))
    print(f"chosen: {chosen['name']} ({reason})")


if __name__ == "__main__":
    main()
